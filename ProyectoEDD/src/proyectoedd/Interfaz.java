    private void BuscarEstActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BuscarEstActionPerformed
        String nombreEstacion = JOptionPane.showInputDialog(this, "Ingrese el nombre de la estación: "); 
        
        if(nombreEstacion != null && !nombreEstacion.trim().isEmpty()){
            Estacion est = tablaHash.buscar(nombreEstacion.trim());
            
            if (est != null){
                JOptionPane.showMessageDialog(this, "Estación encontrada: " + est.getNombre() + "\nLínea: " + est.getLineaMetro());
            
            }else{
                JOptionPane.showMessageDialog(this, "Estación no encontrada.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
            
    }//GEN-LAST:event_BuscarEstActionPerformed

    private void NuevaEstActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_NuevaEstActionPerformed
        String nombre = JOptionPane.showInputDialog(this, "Ingrese el nombre de la nueva estación: ");
        if (nombre != null && !nombre.trim().isEmpty()){
            nombre = nombre.trim();
            if(tablaHash.buscar(nombre) == null){
                Estacion nueva = new Estacion(nombre, nombre, "Línea 1", "General", 0);
                tablaHash.insertar(nombre, nueva);
                grafo.agregarVertice(nombre);
                JOptionPane.showMessageDialog(this, "Estación agregada con éxtio.");
            } else {
                JOptionPane.showMessageDialog(this, "La estación ya existe en el sistema.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_NuevaEstActionPerformed

    private void NuevaConexionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_NuevaConexionActionPerformed
        String origen = JOptionPane.showInputDialog(this, "Nombre de estación de origen:");
        String destino = JOptionPane.showInputDialog(this, "Nombre de estación de destino:");
        String tiempoStr = JOptionPane.showInputDialog(this, "Tiempo de recorrido (minutos):");
        
        if  (origen != null && destino != null && tiempoStr != null){
            try{
                int tiempo = Integer.parseInt(tiempoStr.trim());
                origen = origen.trim();
                destino = destino.trim();
                
                if (tablaHash.buscar(origen) == null){
                    tablaHash.insertar(origen, new Estacion(origen, origen, "Línea 1", "General", 0));   
                }
                if (tablaHash.buscar(destino) == null){
                    tablaHash.insertar(destino, new Estacion(destino, destino, "Línea 1", "General", 0));
                }
                
                grafo.agregarAristaNoDirigida(origen, destino, tiempo);
                JOptionPane.showMessageDialog(this, "Conexión creada exitosamente.");
            } catch (NumberFormatException ex){
                JOptionPane.showMessageDialog(this, "El tiempo debe ser un número entero.", "Error", JOptionPane.ERROR_MESSAGE); 
            }
        }
    }//GEN-LAST:event_NuevaConexionActionPerformed

    private void ModTiempoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ModTiempoActionPerformed
        String origen = JOptionPane.showInputDialog(this, "Estación de origen:");
        String destino = JOptionPane.showInputDialog(this, "Estación de desitno:");
        String tiempoStr = JOptionPane.showInputDialog(this, "Nuevo tiempo (minutos):");
        
        if (origen != null && destino != null && tiempoStr != null){
            try{
                int nuevoTiempo = Integer.parseInt(tiempoStr.trim());
                Vertice vOrigen = grafo.buscarVertice(origen.trim());
                Vertice vDestino = grafo.buscarVertice(destino.trim());
                
                if (vOrigen != null && vDestino != null){
                    boolean cambiado = false;
                    
                    //Actualizar de Origen a Destino
                    NodoLista actualO = vOrigen.getAdyacentes().getCabeza();
                    while(actualO != null){
                        Arista a = (Arista) actualO.getContenido();
                        if (a.getIdDestino().equals(destino.trim())){
                            a.setTiempo(nuevoTiempo);
                            cambiado = true;
                        }
                        actualO = actualO.getSiguiente();  
                    }
                    
                    //Actualizar de Desitno a Origen
                    NodoLista actualD = vDestino.getAdyacentes().getCabeza();
                    while(actualD != null){
                        Arista a = (Arista) actualD.getContenido();
                        if (a.getIdDestino().equals(origen.trim())){
                            a.setTiempo(nuevoTiempo);
                        }
                        actualD = actualD.getSiguiente();
                    }
                    
                    if(cambiado){
                        JOptionPane.showMessageDialog(this, "Tiempo actualizado correctamente.");   
                    } else {
                        JOptionPane.showMessageDialog(this, "No se encontró una conexión directa entre estas estaciones.", "Aviso", JOptionPane.WARNING_MESSAGE);
                    } 
                } else {
                    JOptionPane.showMessageDialog(this, "Una o ambas estaciones no existen.", "Error", JOptionPane.ERROR_MESSAGE);
                }
            } catch (NumberFormatException ex){
                JOptionPane.showMessageDialog(this, "El tiempo debe ser un número entero.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_ModTiempoActionPerformed


